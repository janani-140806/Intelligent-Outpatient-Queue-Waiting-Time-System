"""
Database Seeder Script for AI Hospital Queue & Waiting-Time Prediction System
Pre-populates realistic synthetic healthcare data:
- Departments
- Doctors
- Patients
- Realistic active queue items, completed consultations, and sample appointments.
DISCLAIMER: All patient and medical data generated by this script is completely synthetic.
"""

import os
import sys
import random
from datetime import datetime, timedelta

ROOT_DIR = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
if ROOT_DIR not in sys.path:
    sys.path.insert(0, ROOT_DIR)

from backend.database import SessionLocal, Base, engine
from backend.models.database_models import (
    User, Doctor, Department, Patient, Appointment, QueueItem,
    Consultation, Notification, UserRole, DoctorStatus, AppointmentStatus, QueueStatus
)
from backend.services.auth_service import get_password_hash
from backend.services.queue_service import QueueService

def seed_database():
    print("Initializing database tables...")
    Base.metadata.create_all(bind=engine)
    db = SessionLocal()

    # Clear existing data for clean demo seed
    try:
        db.query(Notification).delete()
        db.query(Consultation).delete()
        db.query(QueueItem).delete()
        db.query(Appointment).delete()
        db.query(Patient).delete()
        db.query(Doctor).delete()
        db.query(Department).delete()
        db.query(User).delete()
        db.commit()
        print("Cleared previous data for fresh seed.")
    except Exception as e:
        db.rollback()
        print(f"Notice during cleanup: {e}")

    # 1. Create Admin Account
    admin_user = User(
        email="admin@hospital.com",
        password_hash=get_password_hash("admin123"),
        role=UserRole.ADMIN.value,
        full_name="Admin Administrator",
        phone="+1 (555) 010-0001"
    )
    db.add(admin_user)
    db.commit()
    db.refresh(admin_user)

    # 2. Create Departments
    departments_data = [
        {"name": "General Medicine", "code": "GM", "desc": "Outpatient primary care, viral fever, hypertension, general consultations", "base_time": 10.0},
        {"name": "Cardiology", "code": "CD", "desc": "Cardiovascular screening, ECG review, chest pain evaluations", "base_time": 18.0},
        {"name": "Pediatrics", "code": "PD", "desc": "Child wellness examinations, pediatric immunization and acute care", "base_time": 12.0},
        {"name": "Orthopedics", "code": "OP", "desc": "Bone, joint disorders, fracture reviews, musculoskeletal assessments", "base_time": 15.0}
    ]

    dept_objs = {}
    for d in departments_data:
        dept = Department(
            name=d["name"],
            code=d["code"],
            description=d["desc"],
            base_consultation_time=d["base_time"],
            is_active=True
        )
        db.add(dept)
        db.flush()
        dept_objs[d["name"]] = dept
    db.commit()

    # 3. Create 5 Doctors
    doctors_info = [
        {
            "name": "Dr. Rajesh Sharma",
            "email": "dr.rajesh@hospital.com",
            "dept": "General Medicine",
            "spec": "Senior Consultant Physician",
            "room": "Room 101",
            "avg_time": 10.0,
            "status": DoctorStatus.AVAILABLE.value
        },
        {
            "name": "Dr. Sarah Jenkins",
            "email": "dr.sarah@hospital.com",
            "dept": "Cardiology",
            "spec": "Interventional Cardiologist",
            "room": "Room 204",
            "avg_time": 18.0,
            "status": DoctorStatus.AVAILABLE.value
        },
        {
            "name": "Dr. Anita Desai",
            "email": "dr.anita@hospital.com",
            "dept": "Pediatrics",
            "spec": "Pediatric Specialist",
            "room": "Room 108",
            "avg_time": 12.0,
            "status": DoctorStatus.AVAILABLE.value
        },
        {
            "name": "Dr. Marcus Vance",
            "email": "dr.marcus@hospital.com",
            "dept": "Orthopedics",
            "spec": "Orthopedic Surgeon & Joint Specialist",
            "room": "Room 302",
            "avg_time": 15.0,
            "status": DoctorStatus.AVAILABLE.value
        },
        {
            "name": "Dr. Emily Chen",
            "email": "dr.emily@hospital.com",
            "dept": "General Medicine",
            "spec": "Family Medicine & Preventive Healthcare",
            "room": "Room 103",
            "avg_time": 11.0,
            "status": DoctorStatus.AVAILABLE.value
        }
    ]

    doctor_objs = []
    for d in doctors_info:
        user = User(
            email=d["email"],
            password_hash=get_password_hash("doctor123"),
            role=UserRole.DOCTOR.value,
            full_name=d["name"],
            phone=f"+1 (555) 010-00{len(doctor_objs)+10}"
        )
        db.add(user)
        db.flush()

        dept = dept_objs[d["dept"]]
        doc = Doctor(
            user_id=user.id,
            department_id=dept.id,
            specialization=d["spec"],
            room_number=d["room"],
            status=d["status"],
            avg_consultation_time=d["avg_time"],
            total_patients_served=14 + len(doctor_objs) * 3
        )
        db.add(doc)
        db.flush()
        doctor_objs.append(doc)
    db.commit()

    # 4. Create Demo Patient (John Doe)
    demo_patient_user = User(
        email="john.doe@example.com",
        password_hash=get_password_hash("patient123"),
        role=UserRole.PATIENT.value,
        full_name="John Doe",
        phone="+1 (555) 012-3456"
    )
    db.add(demo_patient_user)
    db.flush()

    demo_patient = Patient(
        user_id=demo_patient_user.id,
        medical_record_num="MRN-DEMO-001",
        age=34,
        gender="Male",
        blood_group="O+"
    )
    db.add(demo_patient)
    db.flush()

    # 5. Create 30 Synthetic Patients
    first_names = [
        "James", "Mary", "Robert", "Patricia", "Michael", "Jennifer", "William", "Linda",
        "David", "Elizabeth", "Richard", "Barbara", "Joseph", "Susan", "Thomas", "Jessica",
        "Charles", "Sarah", "Christopher", "Karen", "Daniel", "Nancy", "Matthew", "Lisa",
        "Anthony", "Betty", "Mark", "Margaret", "Donald", "Sandra"
    ]
    last_names = [
        "Smith", "Johnson", "Williams", "Brown", "Jones", "Garcia", "Miller", "Davis",
        "Rodriguez", "Martinez", "Hernandez", "Lopez", "Gonzalez", "Wilson", "Anderson",
        "Thomas", "Taylor", "Moore", "Jackson", "Martin", "Lee", "Perez", "Thompson", "White",
        "Harris", "Sanchez", "Clark", "Ramirez", "Lewis", "Robinson"
    ]

    patient_objs = [demo_patient]
    for i in range(len(first_names)):
        fname = first_names[i]
        lname = last_names[i]
        user = User(
            email=f"{fname.lower()}.{lname.lower()}{i+1}@example.com",
            password_hash=get_password_hash("patient123"),
            role=UserRole.PATIENT.value,
            full_name=f"{fname} {lname}",
            phone=f"+1 (555) {random.randint(100, 999)}-{random.randint(1000, 9999)}"
        )
        db.add(user)
        db.flush()

        pat = Patient(
            user_id=user.id,
            medical_record_num=f"MRN-SYN-{i+100:04d}",
            age=random.randint(18, 75),
            gender=random.choice(["Male", "Female"]),
            blood_group=random.choice(["A+", "A-", "B+", "B-", "AB+", "O+", "O-"])
        )
        db.add(pat)
        db.flush()
        patient_objs.append(pat)
    db.commit()

    today_str = datetime.now().strftime("%Y-%m-%d")

    # 6. Create Active Queue for Dr. Rajesh Sharma (General Medicine)
    # Give John Doe an active ticket in Dr. Rajesh's queue
    doc_rajesh = doctor_objs[0] # Dr. Rajesh Sharma
    dept_gm = dept_objs["General Medicine"]

    symptoms_pool = [
        "Persistent dry cough, mild fever for 3 days",
        "Seasonal allergies and sneezing",
        "High blood pressure follow-up",
        "Routine checkup and blood work review",
        "Mild chest discomfort after brisk walking",
        "Pediatric fever and sore throat",
        "Knee pain when ascending stairs",
        "Sprained wrist after light fall",
        "Recurrent migraine headaches"
    ]

    # Pre-populate 4 patients ahead of John Doe
    for pos in range(1, 5):
        pat = patient_objs[pos]
        appt = Appointment(
            appointment_number=f"APT-{datetime.utcnow().strftime('%Y%m%d')}-{pos:04d}",
            patient_id=pat.id,
            doctor_id=doc_rajesh.id,
            department_id=dept_gm.id,
            appointment_date=today_str,
            time_slot="10:00 AM - 10:30 AM",
            status=AppointmentStatus.WAITING.value,
            symptoms=random.choice(symptoms_pool)
        )
        db.add(appt)
        db.flush()

        q_item = QueueItem(
            token_number=f"GM-{pos:03d}",
            appointment_id=appt.id,
            doctor_id=doc_rajesh.id,
            department_id=dept_gm.id,
            queue_position=pos,
            status=QueueStatus.WAITING.value,
            estimated_waiting_time=round(pos * 10.0 * 1.15)
        )
        db.add(q_item)

    # 5th is John Doe!
    john_appt = Appointment(
        appointment_number=f"APT-{datetime.utcnow().strftime('%Y%m%d')}-0005",
        patient_id=demo_patient.id,
        doctor_id=doc_rajesh.id,
        department_id=dept_gm.id,
        appointment_date=today_str,
        time_slot="10:30 AM - 11:00 AM",
        status=AppointmentStatus.WAITING.value,
        symptoms="Persistent dry cough and fatigue for past 4 days."
    )
    db.add(john_appt)
    db.flush()

    john_queue = QueueItem(
        token_number="GM-005",
        appointment_id=john_appt.id,
        doctor_id=doc_rajesh.id,
        department_id=dept_gm.id,
        queue_position=5,
        status=QueueStatus.WAITING.value,
        estimated_waiting_time=48
    )
    db.add(john_queue)
    db.flush()

    # Send Welcome Notification to John
    QueueService.add_notification(
        db=db,
        user_id=demo_patient_user.id,
        title="Token Generated: GM-005",
        message="Your appointment with Dr. Rajesh Sharma is confirmed. You are position #5 in queue. Est. wait time: ~48 mins.",
        notif_type="token"
    )

    # 7. Add queues for other doctors (Cardiology, Pediatrics, Orthopedics)
    token_counters = {"GM": 5, "CD": 0, "PD": 0, "OP": 0}
    
    # Add a patient currently in consultation for Dr. Sarah Jenkins (Cardiology)
    doc_sarah = doctor_objs[1]
    dept_cd = dept_objs["Cardiology"]
    token_counters["CD"] += 1
    sarah_active_pat = patient_objs[6]
    sarah_appt = Appointment(
        appointment_number=f"APT-{datetime.utcnow().strftime('%Y%m%d')}-0010",
        patient_id=sarah_active_pat.id,
        doctor_id=doc_sarah.id,
        department_id=dept_cd.id,
        appointment_date=today_str,
        time_slot="09:30 AM - 10:00 AM",
        status=AppointmentStatus.IN_CONSULTATION.value,
        symptoms="Evaluation of elevated resting heart rate"
    )
    db.add(sarah_appt)
    db.flush()
    doc_sarah.status = DoctorStatus.BUSY.value

    sarah_q = QueueItem(
        token_number=f"CD-{token_counters['CD']:03d}",
        appointment_id=sarah_appt.id,
        doctor_id=doc_sarah.id,
        department_id=dept_cd.id,
        queue_position=0,
        status=QueueStatus.IN_CONSULTATION.value,
        estimated_waiting_time=0,
        actual_consultation_start=datetime.utcnow() - timedelta(minutes=7)
    )
    db.add(sarah_q)

    # Add 3 waiting patients for Cardiology
    for w in range(1, 4):
        token_counters["CD"] += 1
        pat = patient_objs[6 + w]
        c_appt = Appointment(
            appointment_number=f"APT-{datetime.utcnow().strftime('%Y%m%d')}-{10+w:04d}",
            patient_id=pat.id,
            doctor_id=doc_sarah.id,
            department_id=dept_cd.id,
            appointment_date=today_str,
            time_slot="10:30 AM - 11:00 AM",
            status=AppointmentStatus.WAITING.value,
            symptoms=random.choice(symptoms_pool)
        )
        db.add(c_appt)
        db.flush()
        db.add(QueueItem(
            token_number=f"CD-{token_counters['CD']:03d}",
            appointment_id=c_appt.id,
            doctor_id=doc_sarah.id,
            department_id=dept_cd.id,
            queue_position=w,
            status=QueueStatus.WAITING.value,
            estimated_waiting_time=round(w * 18.0 * 1.1)
        ))

    # Add 3 completed consultations today with prescriptions
    doc_anita = doctor_objs[2] # Pediatrics
    dept_pd = dept_objs["Pediatrics"]
    for comp in range(1, 4):
        token_counters["PD"] += 1
        pat = patient_objs[12 + comp]
        comp_appt = Appointment(
            appointment_number=f"APT-{datetime.utcnow().strftime('%Y%m%d')}-{30+comp:04d}",
            patient_id=pat.id,
            doctor_id=doc_anita.id,
            department_id=dept_pd.id,
            appointment_date=today_str,
            time_slot="08:30 AM - 09:00 AM",
            status=AppointmentStatus.COMPLETED.value,
            symptoms="Mild viral rhinorrhea and cough"
        )
        db.add(comp_appt)
        db.flush()

        comp_q = QueueItem(
            token_number=f"PD-{token_counters['PD']:03d}",
            appointment_id=comp_appt.id,
            doctor_id=doc_anita.id,
            department_id=dept_pd.id,
            queue_position=0,
            status=QueueStatus.COMPLETED.value,
            estimated_waiting_time=0,
            actual_consultation_start=datetime.utcnow() - timedelta(minutes=60 + comp*15),
            actual_consultation_end=datetime.utcnow() - timedelta(minutes=48 + comp*15)
        )
        db.add(comp_q)
        db.flush()

        db.add(Consultation(
            queue_item_id=comp_q.id,
            doctor_id=doc_anita.id,
            patient_id=pat.id,
            duration_minutes=12.0,
            diagnosis="Acute upper respiratory tract infection, viral etiology.",
            prescription="Paracetamol syrup 5ml PRN for temperature > 38C, saline nasal drops 3x/day.",
            notes="Hydration advised. Review in 5 days if cough persists."
        ))

    # Add 1 no-show / skipped
    pat_skip = patient_objs[18]
    skip_appt = Appointment(
        appointment_number=f"APT-{datetime.utcnow().strftime('%Y%m%d')}-0099",
        patient_id=pat_skip.id,
        doctor_id=doc_rajesh.id,
        department_id=dept_gm.id,
        appointment_date=today_str,
        time_slot="09:00 AM - 09:30 AM",
        status=AppointmentStatus.NO_SHOW.value,
        symptoms="Routine prescription refill"
    )
    db.add(skip_appt)
    db.flush()
    db.add(QueueItem(
        token_number="GM-000",
        appointment_id=skip_appt.id,
        doctor_id=doc_rajesh.id,
        department_id=dept_gm.id,
        queue_position=0,
        status=QueueStatus.SKIPPED.value,
        estimated_waiting_time=0
    ))

    db.commit()
    print("Database seeding completed successfully!")
    print("\n--- Demo Credentials ---")
    print("Admin:   admin@hospital.com   / admin123")
    print("Doctor:  dr.rajesh@hospital.com / doctor123 (Dr. Rajesh Sharma, General Medicine)")
    print("Doctor:  dr.sarah@hospital.com  / doctor123 (Dr. Sarah Jenkins, Cardiology)")
    print("Patient: john.doe@example.com   / patient123 (John Doe - Active Token GM-005)")

